/* さぼてんきくん（ドット絵）。ほかのサイトからは、何も読みこみません。
   <canvas data-face="kaiteki"> のような場所に、16x16の絵をかきます。
   絵が2まいあるもの（kaiteki と kaiteki2 など）は、半秒ごとに切りかえて動かします。
   data-color="oled" をつけると、画面（OLED）のような水色でかきます。 */
(function () {
  var N = 16;
  var MARKS = window.SABO_MARKS = {
    kaiteki: ["0000000110000000", "0000001111000000", "0000011111100000", "0110010110100000", "0110010110100110", "0110011111100110", "0110010110100110", "0111111001100110", "0011111111111110", "0000011111111100", "0000011111100000", "0000011111100000", "0011111111111100", "0001000000001000", "0001000000001000", "0000111111110000"],
    kaiteki2: ["0000000110000000", "0000001111000000", "0000011111100000", "0000010110100110", "0110010110100110", "0110011111100110", "0110010110100110", "0110011001111110", "0111111111111100", "0011111111100000", "0000011111100000", "0000011111100000", "0011111111111100", "0001000000001000", "0001000000001000", "0000111111110000"],
    jimejime: ["0100000110000000", "0011001111000110", "0000011111101000", "0011010110100000", "0110010110101100", "0110011111100110", "0110010000100110", "0111111111100110", "0011111111111110", "0000011111111100", "0000011111100000", "0000011111100000", "0011111111111100", "0001000000001000", "0001000000001000", "0000111111110000"],
    jimejime2: ["1000000110000000", "0100001111000010", "0000011111100100", "0110011111100000", "0110010110100110", "0110011111100110", "0110010000100110", "0111111111100110", "0011111111111110", "0000011111111100", "0000011111100000", "0000011111100000", "0011111111111100", "0001000000001000", "0001000000001000", "0000111111110000"],
    karakara: ["0000000110001000", "0010001111000100", "0100011111101000", "0010011111100100", "0100010110100000", "0000011111111100", "0011111001111110", "0111110000100110", "0110011111100110", "0110011111100110", "0110011111100000", "0000011111100000", "0011111111111100", "0001000000001000", "0001000000001000", "0000111111110000"],
    karakara2: ["0000000110000100", "0100001111001000", "0010011111100100", "0100011111101000", "0010010110100000", "0000011111111100", "0011111001111110", "0111110110100110", "0110011111100110", "0110011111100110", "0110011111100000", "0000011111100000", "0011111111111100", "0001000000001000", "0001000000001000", "0000111111110000"]
  };
  var reduce = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  var canvases = [].slice.call(document.querySelectorAll("canvas[data-face]"));
  var frame = 0;

  function fillColor(cv) {
    return cv.getAttribute("data-color") === "oled" ? "#9fe3ff" : getComputedStyle(cv).color;
  }
  function paint(cv) {
    var key = cv.getAttribute("data-face");
    var rows = (frame && MARKS[key + "2"]) ? MARKS[key + "2"] : MARKS[key];
    if (!rows) return;
    var ctx = cv.getContext("2d");
    ctx.clearRect(0, 0, N, N);
    ctx.fillStyle = fillColor(cv);
    for (var y = 0; y < N; y++) {
      for (var x = 0; x < N; x++) {
        if (rows[y].charAt(x) === "1") ctx.fillRect(x, y, 1, 1);
      }
    }
  }
  function paintAll() { canvases.forEach(paint); }

  canvases.forEach(function (cv) { cv.width = N; cv.height = N; });
  paintAll();

  // 動きを減らす設定の人には、止めたまま出す
  if (!reduce) {
    setInterval(function () {
      if (document.hidden) return;
      frame = 1 - frame;
      paintAll();
    }, 500);
  }

  // ダークモードが切りかわったら、色をかきなおす
  if (window.matchMedia) {
    var mq = window.matchMedia("(prefers-color-scheme: dark)");
    if (mq.addEventListener) mq.addEventListener("change", paintAll);
    else if (mq.addListener) mq.addListener(paintAll);
  }
})();
